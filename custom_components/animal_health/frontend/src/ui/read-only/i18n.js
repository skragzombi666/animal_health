export const MESSAGES = Object.freeze({ de: DE, en: EN });

export function languageKey(value) {
  return String(value ?? "en").toLocaleLowerCase().startsWith("de")
    ? "de"
    : "en";
}

export function createTranslator(languageCode = "en") {
  const dictionary = MESSAGES[languageKey(languageCode)];
  return (key, replacements = {}) => {
    const template = dictionary[key] ?? String(key);
    return Object.entries(replacements).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template,
    );
  };
}
